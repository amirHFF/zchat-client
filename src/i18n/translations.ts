export function interpolate(
  template: string,
  params?: Record<string, string | number>,
): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) =>
    params[token] !== undefined ? String(params[token]) : `{{${token}}}`,
  );
}
